def insert_sort(alist):
    n = len(alist)
    for j in range(1, n):
        i = j
        while i>0:
            if alist[i-1] > alist[i]:
                # the new one element is smaller
                alist[i-1], alist[i] = alist[i], alist[i-1]
                i -=1
            else:
                # the new one element is larger, so it is no need to change
                break

    return alist

alist1 = [54,226,93,17,77,313,44,55,11]
print(insert_sort(alist1))

